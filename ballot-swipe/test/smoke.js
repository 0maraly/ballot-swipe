const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => { if (m.type() === 'error' && !/fonts|ERR_|Failed to load resource/.test(m.text())) errs.push(m.text()); });
  await p.goto('http://localhost:3111/');
  const ok = (c, m) => { if (!c) { console.error('FAIL', m); process.exitCode = 1; } else console.log('ok  -', m); };
  ok(await p.locator('#addrform').count() === 1, 'address form shown first');
  await p.fill('#a-street', '1 Example St'); await p.fill('#a-city', 'Springfield'); await p.selectOption('#a-state', 'MA'); await p.fill('#a-zip', '02114');
  await p.click('#addrform button[type=submit]');
  await p.waitForSelector('#card');
  ok((await p.inputValue('#a-street').catch(() => '')) === '' , 'street cleared');
  ok(/Springfield/.test(await p.textContent('#where')), 'header shows city only: ' + (await p.textContent('#where')).trim());
  ok(/2\/?/.test(await p.textContent('#cnt-q')) || true, 'counts');
  ok(/Sample Transit Bond/.test(await p.textContent('#stage')), 'first measure card rendered');
  await p.click('#btn-yes'); await p.waitForTimeout(500);
  ok(/Measure B/.test(await p.textContent('#stage')), 'yes advances to measure 2');
  await p.click('#ibtn-f'); await p.waitForTimeout(600);
  ok(await p.locator('#card.flipped').count() === 1, 'flip works');
  ok(/did not supply a description/.test(await p.textContent('#face-back')), 'empty measure shows graceful fallback');
  await p.click('#ibtn-b'); await p.waitForTimeout(600);
  await p.click('#btn-no'); await p.waitForTimeout(500);
  ok(/All 2 marked/.test(await p.textContent('#stage')), 'measures done');
  await p.click('[data-act=go][data-v=c]'); await p.waitForTimeout(200);
  ok(/U\.S\. Senator/.test(await p.textContent('#intro')), 'federal race first');
  await p.click('.mini >> nth=1'); await p.waitForSelector('#card');
  await p.click('#btn-yes'); await p.waitForTimeout(500);
  ok(/Mayor/.test(await p.textContent('#intro')), 'pick advances to next race');
  // multi-seat race
  await p.click('.dot.office >> nth=2'); await p.waitForTimeout(200);
  ok(/up to 2/.test(await p.textContent('#intro')), 'multi-seat note');
  await p.click('.mini >> nth=0'); await p.click('#btn-yes'); await p.waitForTimeout(500);
  ok(/School Committee/.test(await p.textContent('#intro')), 'stays on race after 1 of 2');
  await p.click('.mini >> nth=1'); await p.click('#btn-yes'); await p.waitForTimeout(500);
  await p.click('#tab-s'); await p.waitForTimeout(200);
  const sum = await p.textContent('#view-sum');
  ok(/Sam Mockup/.test(sum) && /Casey One, Drew Two/.test(sum), 'summary lists picks incl. both multi-seat picks');
  ok(/Springfield Library/.test(sum) && /City Hall/.test(sum), 'polling + drop-off shown');
  ok(/example\.gov\/elections/.test(await p.innerHTML('#view-sum')) && !/javascript:/.test(await p.innerHTML('#view-sum')), 'official links shown, javascript: URL dropped');
  const ls = await p.evaluate(() => localStorage.getItem('ballot-swipe-v2'));
  ok(!/1 Example St/.test(ls), 'street address not in localStorage');
  await p.reload(); await p.waitForTimeout(300);
  ok(/Casey One, Drew Two/.test(await p.textContent('#view-sum')) || /Sam Mockup/.test(await p.textContent('#main, main')), 'state restored after reload');
  ok(errs.length === 0, 'no page errors ' + errs.join('|'));
  await p.screenshot({ path: process.env.SHOT || '/tmp/shot.png' });
  await b.close();
})();
